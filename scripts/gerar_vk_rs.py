#!/usr/bin/env python3
"""Write contracts/groth16-verifier/src/vk.rs from circuits/setup/vk.json (T-037).

The verifier embeds the verification key as constants, the way kleroterion
embeds the beacon key (INV-10): nobody deploying it can hand it another key.
The byte layout is the Soroban BN254 host's: G1 = be(x) || be(y), G2 =
be(x.c1) || be(x.c0) || be(y.c1) || be(y.c0). G8 checks vk.rs still matches.

    python3 scripts/gerar_vk_rs.py

No dependencies.
"""

import json
import pathlib

RAIZ = pathlib.Path(__file__).resolve().parent.parent
VK = RAIZ / "circuits" / "setup" / "vk.json"
SAIDA = RAIZ / "contracts" / "groth16-verifier" / "src" / "vk.rs"


def be32(n):
    return int(n).to_bytes(32, "big")


def g1(p):
    return be32(p[0]) + be32(p[1])


def g2(p):
    return be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0])


def arr(b):
    linhas = []
    for i in range(0, len(b), 16):
        linhas.append("    " + ", ".join(f"0x{x:02x}" for x in b[i : i + 16]) + ",")
    return "[\n" + "\n".join(linhas) + "\n]"


def main():
    vk = json.loads(VK.read_text())
    assert vk["protocol"] == "groth16" and vk["curve"] == "bn128" and vk["nPublic"] == 4
    partes = [
        "// Generated by scripts/gerar_vk_rs.py from circuits/setup/vk.json (T-036 setup,",
        "// circuits/setup/TRANSCRICAO.md). Do not edit: re-run the script.",
        "",
        f"pub const ALPHA: [u8; 64] = {arr(g1(vk['vk_alpha_1']))};",
        f"pub const BETA: [u8; 128] = {arr(g2(vk['vk_beta_2']))};",
        f"pub const GAMMA: [u8; 128] = {arr(g2(vk['vk_gamma_2']))};",
        f"pub const DELTA: [u8; 128] = {arr(g2(vk['vk_delta_2']))};",
        f"pub const IC: [[u8; 64]; {len(vk['IC'])}] = [",
        *[f"    {arr(g1(p))}," .replace("\n", "\n    ") for p in vk["IC"]],
        "];",
        "",
    ]
    SAIDA.write_text("\n".join(partes))
    print(f"wrote {SAIDA.relative_to(RAIZ)}")


if __name__ == "__main__":
    main()
