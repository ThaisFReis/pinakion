#!/usr/bin/env python3
"""Export the Poseidon BN254 constants the contract embeds to tests/poseidon-bn254.json.

The off-chain recomputations (scripts/poseidon.py, web/poseidon.mjs) read that
JSON, so all three use the very constants in contracts/poseidon/src/params.rs
(Apache-2.0, from stellar/rs-soroban-poseidon v28.0.0 — see that file).

    python3 scripts/exportar_constantes_poseidon.py

No dependencies.
"""

import json
import pathlib
import re

RAIZ = pathlib.Path(__file__).resolve().parent.parent
PARAMS = RAIZ / "contracts" / "poseidon" / "src" / "params.rs"
SAIDA = RAIZ / "tests" / "poseidon-bn254.json"


def matriz(fonte, nome):
    corpo = fonte[fonte.index(f"fn {nome}("):]
    corpo = corpo[: corpo.index("\n}\n")]
    linhas = []
    for bloco in re.split(r"\n\s*vec!\[e,\s*\n", corpo)[1:]:
        linhas.append(["0x" + h for h in re.findall(r"0x([0-9a-f]{64})", bloco)])
    return [l for l in linhas if l]


def main():
    fonte = PARAMS.read_text()
    dados = {
        "_": "Poseidon over BN254 as circomlib defines it, copied from contracts/poseidon/src/params.rs (Apache-2.0, Stellar Development Foundation, rs-soroban-poseidon v28.0.0). Generated by scripts/exportar_constantes_poseidon.py.",
        "r": "0x30644e72e131a029b85045b68181585d2833e84879b9709143e1f593f0000001",
        "d": 5,
        "t2": {"rounds_f": 8, "rounds_p": 56,
               "mds": matriz(fonte, "get_mds_bn254_t_2"), "rc": matriz(fonte, "get_rc_bn254_t_2")},
        "t3": {"rounds_f": 8, "rounds_p": 57,
               "mds": matriz(fonte, "get_mds_bn254_t_3"), "rc": matriz(fonte, "get_rc_bn254_t_3")},
    }
    for t, largura, rodadas in [("t2", 2, 64), ("t3", 3, 65)]:
        assert len(dados[t]["mds"]) == largura and all(len(l) == largura for l in dados[t]["mds"]), t
        assert len(dados[t]["rc"]) == rodadas and all(len(l) == largura for l in dados[t]["rc"]), t
    SAIDA.write_text(json.dumps(dados, indent=1) + "\n")
    print(f"wrote {SAIDA.relative_to(RAIZ)}")


if __name__ == "__main__":
    main()
